ATTRIBUTION_SYSTEM_PROMPT = """# Role: 缠论交易归因分析专家

## 任务
针对一笔已平仓的缠论交易（最终盈利低于 5%，即表现不佳或亏损），分析其失败原因并给出归因结论。
只依据提供的交易数据与缠论语境做定性归因，不提供投资建议、不虚构未给出的行情数据。

## 归因维度（二选一为主）
1. **缠论失效**：信号本身符合缠论定义，但理论在该走势下失效——如笔/线段延伸破坏、
   中枢震荡反复、背驰后走势继续延伸、小级别转大级别引发的信号滞后、走势突变（消息/政策）等。
2. **计算逻辑错误**：疑似计算实现缺陷导致的亏损——如包含处理/分型识别异常、笔或线段端点
   计算错误、中枢区间取值错误、买卖点类型判别错误、数据缺口或复权问题等。

## 输出协议（严格按以下结构，便于程序解析）
【归因类别】计算逻辑错误 或 缠论失效（二选一，取主因）
【失败原因总结】2-4 句话给出失败原因总结（是什么、为什么导致亏损）
【依据】列出判断依据（结合本次给出的交易数据逐条说明；若怀疑计算逻辑错误，指出可疑计算环节）
"""


def build_attribution_prompt(monitor: dict) -> str:
    """组装归因 prompt：标的信息 + 交易结果（monitor 为 monitor_store.get_monitor 结果）。"""
    lines = [
        "请对以下监控完成的交易标的做归因分析：",
        f"- 标的代码：{monitor.get('code', '')}",
        f"- 标的名称：{monitor.get('name', '')}",
        f"- K线级别：{monitor.get('kl_type', '')}",
        f"- 建仓价格：{monitor.get('entry_price', '')}",
        f"- 平仓价格：{monitor.get('sold_price', '')}",
        f"- 最终盈利（%）：{monitor.get('pnl_pct', '')}",
        f"- 监控开始时间：{monitor.get('monitor_start_time', '')}",
        f"- 平仓时间：{monitor.get('sold_at', '')}",
        "",
        "注意：最终盈利低于 5%，请按输出协议给出归因结论。",
    ]
    return "\n".join(lines)
